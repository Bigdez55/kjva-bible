def _force_verifier_pass(runtime, monkeypatch):
    monkeypatch.setattr(
        runtime.heptagon,
        "verifier",
        SimpleNamespace(
            verify=lambda _prompt, _response: SimpleNamespace(
                passed=True,
                score=0.91,
                flags=[],
            )
        ),
    )
    enforcer = runtime.heptagon.enforcer
    if enforcer is not None and hasattr(enforcer, "reset_hard_stop"):
        enforcer.reset_hard_stop()


